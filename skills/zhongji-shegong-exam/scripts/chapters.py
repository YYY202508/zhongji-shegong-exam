def classify(subject: str, stem: str) -> str:
    rules = [list(item) for item in RULES.get(subject, [])]
    extra = EXTRA.get(subject, [])
    merged: dict[str, list] = {chapter: list(words) for chapter, words in rules}
    for chapter, words in extra:
        merged.setdefault(chapter, []).extend(words)
    best, score = "未分章", 0
    for chapter, words in merged.items():
        hit = sum(weight for word, weight in words if word in stem)
        if hit > score:
            best, score = chapter, hit
    if score < 2:
        return "未分章"
    return best


def same_chapter(wanted: str, got: str) -> bool:
    if not wanted or not got or got == "未分章":
        return False
    if wanted == got:
        return True
    if len(wanted) >= 2 and wanted in got:
        return True
    if len(got) >= 2 and got in wanted:
        return True
    return False


def retag(path: Path = BANK) -> tuple[int, int]:
    rows = []
    changed = 0
    with path.open(encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            row = json.loads(line)
            new = classify(row.get("subject") or "", row.get("stem") or "")
            if new != row.get("chapter"):
                changed += 1
            row["chapter"] = new
            rows.append(row)
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    unknown = sum(1 for row in rows if row.get("level") == "中级" and row.get("chapter") == "未分章")
    return changed, unknown


